    /**
     * Mendapatkan statistik KPI monitoring telemetri
     */
    public static function getStatistik()
    {
        $posList = self::getDaftarPos();
        $total = count($posList);
        $online = 0;
        $offline = 0;
        $waspada = 0;
        $siaga = 0;
        $awas = 0;

        foreach ($posList as $pos) {
            if ($pos['status_alat'] === 'Online') {
                $online++;
            } else {
                $offline++;
            }

            if ($pos['status_siaga'] === 'Waspada') {
                $waspada++;
            } elseif ($pos['status_siaga'] === 'Siaga') {
                $siaga++;
            } elseif ($pos['status_siaga'] === 'Awas') {
                $awas++;
            }
        }

        $totalAwlr = count(array_filter($posList, fn($p) => $p['tipe'] === 'AWLR'));
        $totalArr  = count(array_filter($posList, fn($p) => $p['tipe'] === 'ARR'));
        $totalPch  = count(array_filter($posList, fn($p) => $p['tipe'] === 'PDA_PCH'));

        return [
            'total_pos' => $total,
            'pos_online' => $online,
            'pos_offline' => $offline,
            'persen_online' => $total > 0 ? round(($online / $total) * 100) : 0,
            'total_awlr' => $totalAwlr,
            'total_arr' => $totalArr,
            'total_pch' => $totalPch,
            'total_siaga_kritis' => $waspada + $siaga + $awas,
            'peringatan' => [
                [
                    'pos' => 'AWLR Kembayan (Sanggau)',
                    'status' => 'Waspada',
                    'badge' => 'warning',
                    'detail' => 'TMA: 28.52 m (Ambang Waspada: 28.00 m)',
                ],
                [
                    'pos' => 'AWLR Nanga Pinoh (Melawi)',
                    'status' => 'Siaga',
                    'badge' => 'danger',
                    'detail' => 'TMA: 6.20 m (Ambang Siaga: 6.00 m)',
                ],
                [
                    'pos' => 'ARR Ambawang (Kubu Raya)',
                    'status' => 'Waspada',
                    'badge' => 'warning',
                    'detail' => 'Curah Hujan: 38.5 mm/jam (Hujan Lebat)',
                ],
            ],
        ];
    }

